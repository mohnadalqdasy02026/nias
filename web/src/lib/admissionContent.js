export function admissionKeyFor(programType) {
  if (programType === 'bachelor') return 'bachelor';
  if (programType === 'diploma') return 'diploma';
  return 'master';
}

export function linesToText(list) {
  return Array.isArray(list) ? list.join('\n') : String(list ?? '');
}

export function textToLines(text) {
  return String(text ?? '')
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean);
}
