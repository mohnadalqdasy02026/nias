export function bodyToText(body) {
  return Array.isArray(body) ? body.join('\n') : String(body ?? '');
}

export function textToBody(text) {
  return String(text ?? '')
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean);
}
