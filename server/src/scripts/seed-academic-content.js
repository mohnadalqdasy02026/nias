async function main() {
  const client = new pg.Client({ connectionString: DATABASE_URL });
  await client.connect();

  let collegesUpdated = 0;
  let departmentsUpdated = 0;
  let departmentsSkipped = 0;
  let programsSeeded = 0;
  let programsSkipped = [];

  try {
    await client.query('BEGIN');

    for (const [name, content] of Object.entries(COLLEGE_CONTENT)) {
      const { rows } = await client.query(
        `UPDATE colleges
            SET about = COALESCE(NULLIF(about, ''), $2),
                vision = COALESCE(NULLIF(vision, ''), $3),
                mission = COALESCE(NULLIF(mission, ''), $4)
          WHERE name_ar = $1`,
        [name, content.about, content.vision, content.mission],
      );
      if (rows.length) collegesUpdated += rows.length;
    }

    for (const [name, content] of Object.entries(DEPARTMENTS)) {
      const { rows } = await client.query(
        `UPDATE departments
            SET description = COALESCE(NULLIF(description, ''), $2),
                head_name_ar = COALESCE(NULLIF(head_name_ar, ''), $3),
                head_title = COALESCE(NULLIF(head_title, ''), $4)
          WHERE name_ar = $1
             OR name_ar = 'قسم ' || $1
             OR name_ar LIKE $1 || ' %'
             OR name_ar LIKE 'قسم ' || $1 || ' %'
          RETURNING id`,
        [name, content.description, content.head_name_ar, content.head_title],
      );
      if (rows.length) departmentsUpdated += rows.length;
      else departmentsSkipped += 1;
    }

    const { rows: programs } = await client.query(
      `SELECT id, name_ar FROM academic_programs WHERE deleted_at IS NULL`,
    );
    for (const program of programs) {
      const plan = STUDY_PLANS[program.name_ar];
      if (!plan) {
        programsSkipped.push(program.name_ar);
        continue;
      }
      const { rows: [{ n }] } = await client.query(
        'SELECT count(*)::int AS n FROM program_courses WHERE program_id = $1',
        [program.id],
      );
      if (n > 0) {
        programsSkipped.push(program.name_ar);
        continue;
      }
      for (const [level, sem, code, name, hours] of plan) {
        await client.query(
          `INSERT INTO program_courses (program_id, level_no, semester_no, course_code, name_ar, credit_hours)
           VALUES ($1, $2, $3, $4, $5, $6)`,
          [program.id, level, sem, code, name, hours],
        );
      }
      programsSeeded += 1;
    }

    await client.query('COMMIT');
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    await client.end();
  }

  console.log(`Colleges enriched: ${collegesUpdated}`);
  console.log(`Departments updated: ${departmentsUpdated} (missing: ${departmentsSkipped})`);
  console.log(`Study plans seeded: ${programsSeeded}`);
  if (programsSkipped.length) console.log(`Programs skipped: ${programsSkipped.join(', ')}`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});